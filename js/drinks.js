function slugify(s) {
  return s
    .toLowerCase()
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");
}

const DRINKS = [];
for (const cat of CATEGORIES) {
  for (const [name, pts, note] of RAW_DRINKS[cat.id]) {
    DRINKS.push({ id: slugify(name), name, pts, note: note || "", cat: cat.id, alc: cat.alc });
  }
}

// Intensity tiers shown on every drink tile.
const TIERS = [
  { min: 1, label: "Tempe Breeze", flames: 1 },
  { min: 2, label: "Mill Ave Buzz", flames: 2 },
  { min: 3, label: "Spring Break", flames: 3 },
  { min: 4, label: "Frat Row", flames: 4 },
  { min: 5, label: "Hellfire", flames: 5 },
];

function tierFor(pts) {
  let t = TIERS[0];
  for (const tier of TIERS) if (pts >= tier.min) t = tier;
  return t;
}
